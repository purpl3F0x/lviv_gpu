package lviv_gpu_modules

import spinal.core._
import spinal.lib._
import spinal.lib.bus.amba3.apb._
import spinal.lib.bus.regif._
import spinal.lib.bus.regif.AccessType._

object ApbThreadRegs {
  val byteCount = 32 // APB window: 8 words
}

class ApbThreadRegs(threadClockDomain: ClockDomain) extends Component {
  val s_apb = slave(Apb3(Apb3Config(addressWidth = log2Up(ApbThreadRegs.byteCount), dataWidth = 32)))

  val thread_busy = in Bool () // thread_clk domain
  val zbuf_clear_busy = in Bool () // thread_clk domain
  val zbuf_clear = out Bool () // thread_clk domain
  val thread_soft_reset = out Bool () // thread_clk domain
  val cache_flush = out Bool () // thread_clk domain

  val busif = Apb3BusInterface(s_apb, (0x0000, ApbThreadRegs.byteCount), "THREAD")

  // 0x00: STATUS
  val REG_STATUS = busif.newRegAt(address = 0x00, doc = "Thread Status and Soft Reset Register")
  val BUSY =
    REG_STATUS.field(Bool(), RO, doc = "Read thread status (0: empty, 1: busy); write 1 to reset the thread core")
  BUSY := BufferCC(thread_busy, init = False)
  val threadSoftResetPulse = RegNext(REG_STATUS.hitDoWrite && busif.writeData(0)) init (False)
  thread_soft_reset := PulseCCByToggle(threadSoftResetPulse, ClockDomain.current, threadClockDomain)

  // 0x04: ZBUF_CLEAR
  val REG_ZBUF = busif.newRegAt(address = 0x04, doc = "Z-Buffer Control Register")
  val ZBUF_CLEAR =
    REG_ZBUF.field(Bool(), RO, doc = "Write 1 to reset the Z-buffer; reads 1 while the reset is in progress")
  ZBUF_CLEAR := BufferCC(zbuf_clear_busy, init = False)
  // RO field for readback, write-1 pulse generated by hand since regif has no RO+W1P type
  val zbufClearPulse = RegNext(REG_ZBUF.hitDoWrite && busif.writeData(0)) init (False)
  zbuf_clear := PulseCCByToggle(zbufClearPulse, ClockDomain.current, threadClockDomain)

  // 0x08: CACHE
  val REG_CACHE = busif.newRegAt(address = 0x08, doc = "Cache Control Register")
  val CACHE_FLUSH = REG_CACHE.field(Bool(), WO, doc = "Write 1 to flush the cache")
  REG_CACHE.reserved(31 bits)
  val cacheFlushPulse = RegNext(REG_CACHE.hitDoWrite && busif.writeData(0)) init (False)
  cache_flush := PulseCCByToggle(cacheFlushPulse, ClockDomain.current, threadClockDomain)

  // 0x0C: reserved
  val REG_RESERVED_0C = busif.newRegAt(address = 0x0c, doc = "Reserved")
  REG_RESERVED_0C.reserved(32 bits)

  // 0x10 - 0x1C: reserved for cache perf counters (not implemented yet)
  val REG_CACHE_HITS = busif.newRegAt(address = 0x10, doc = "Reserved: cache hit counter (not implemented)")
  REG_CACHE_HITS.reserved(32 bits)
  val REG_CACHE_MISSES = busif.newRegAt(address = 0x14, doc = "Reserved: cache miss counter (not implemented)")
  REG_CACHE_MISSES.reserved(32 bits)
  val REG_CACHE_EVICTIONS =
    busif.newRegAt(address = 0x18, doc = "Reserved: cache eviction counter (not implemented)")
  REG_CACHE_EVICTIONS.reserved(32 bits)
  val REG_CACHE_STALL_CYCLES =
    busif.newRegAt(address = 0x1c, doc = "Reserved: cache stall cycle counter (not implemented)")
  REG_CACHE_STALL_CYCLES.reserved(32 bits)

  busif.accept(HtmlGenerator("apb_thread_regmap", "THREAD"))
  busif.accept(CHeaderGenerator("apb_thread_regmap", "THREAD"))
  busif.accept(JsonGenerator("apb_thread_regmap"))
}

object ApbThreadRegsVerilog extends App {
  SpinalConfig(
    targetDirectory = "rtl/ApbThreadRegs",
    defaultConfigForClockDomains = ClockDomainConfig(
      resetActiveLevel = LOW,
      resetKind = SYNC
    )
  ).withPrivateNamespace.generateVerilog(new ApbThreadRegs(ClockDomain.external("thread")))
}
