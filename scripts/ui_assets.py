"""Fonts and files for sdk/src/ui.h's users, as C headers.

font: a monospace TrueType font rasterized without antialiasing into CELL_W x CELL_H cells (a
ui_font_t): the printable ASCII characters, and below them code page 437's pointers (0x10 right, 0x11
left) and arrows (0x18 up, 0x19 down, 0x1A right, 0x1B left); blank where the font has no glyph. Each
glyph: CELL_H rows of whole bytes, the leftmost pixel the first byte's MSB. The font's copyright and
license, from its name table, go into the header.
data: a file's bytes as they are, e.g. a PNG for stb_image to decode in the program.

Usage: python scripts/ui_assets.py font FONT.ttf SIZE CELL_W CELL_H NAME OUT.h   (Pillow, fontTools)
       python scripts/ui_assets.py data FILE NAME OUT.h
"""

import argparse
import os
import textwrap

FIRST, LAST = 0x10, 0x7E
SYMBOLS = {0x10: 0x25BA, 0x11: 0x25C4, 0x18: 0x2191, 0x19: 0x2193, 0x1A: 0x2192, 0x1B: 0x2190}


def comment(text):
    lines = [wrapped for line in text.splitlines() for wrapped in textwrap.wrap(line, 97) or [""]]
    return "".join(f"// {line}".rstrip() + "\n" for line in lines)


def array(values, per_line, fmt):
    lines = []
    for i in range(0, len(values), per_line):
        lines.append("    " + ", ".join(fmt.format(v) for v in values[i : i + per_line]) + ",")
    return "\n".join(lines)


def font(args):
    from fontTools.ttLib import TTFont
    from PIL import Image, ImageDraw, ImageFont

    names = TTFont(args.font)["name"]
    cmap = TTFont(args.font).getBestCmap()
    face = ImageFont.truetype(args.font, args.size)
    ascent, descent = face.getmetrics()
    w, h = args.cell_w, args.cell_h
    top = (h - ascent - descent) // 2
    row_bytes = (w + 7) // 8
    data, missing, clipped = [], [], []
    for code in range(FIRST, LAST + 1):
        point = SYMBOLS.get(code, code if code >= 0x20 else None)
        # Drawn in a canvas with a cell's margin all round: what lands outside the cell is clipped
        canvas = Image.new("1", (3 * w, 3 * h), 0)
        if point is not None and point in cmap:
            draw = ImageDraw.Draw(canvas)
            draw.fontmode = "1"  # no antialiasing
            left = round((w - face.getlength(chr(point))) / 2)
            draw.text((w + left, h + top), chr(point), font=face, fill=1)
            box = canvas.getbbox()
            if box and (box[0] < w or box[1] < h or box[2] > 2 * w or box[3] > 2 * h):
                clipped.append(chr(point) if 0x20 < point < 0x7F else f"U+{point:04X}")
        elif point is not None:
            missing.append(f"U+{point:04X}")
        cell = canvas.crop((w, h, 2 * w, 2 * h))
        for y in range(h):
            bits = 0
            for x in range(w):
                bits = bits << 1 | (1 if cell.getpixel((x, y)) else 0)
            bits <<= 8 * row_bytes - w
            data += [(bits >> (8 * (row_bytes - 1 - i))) & 0xFF for i in range(row_bytes)]
    if missing:
        print("not in the font, blank: " + " ".join(missing))
    if clipped:
        print("cut at the cell's edge: " + " ".join(clipped))

    def name_record(i):
        record = names.getName(i, 3, 1, 0x409) or names.getName(i, 1, 0, 0)
        return str(record) if record else ""

    source = os.path.basename(args.font)
    with open(args.out, "w", newline="\n") as f:
        f.write(f"// Generated by scripts/ui_assets.py from {source} at {args.size} px: {w} x {h} cells,\n")
        f.write(f"// characters 0x{FIRST:02X} to 0x{LAST:02X}.\n//\n")
        f.write(comment(name_record(0)))
        notice = name_record(13)
        if notice:
            f.write("//\n" + comment(notice))
        f.write("#pragma once\n\n#include \"ui.h\"\n\n")
        f.write(f"static const uint8_t {args.name}_bitmap[] = {{\n{array(data, 16, '0x{:02X}')}\n}};\n\n")
        f.write(f"static const ui_font_t {args.name} = {{{args.name}_bitmap, {w}, {h}, {FIRST}, {LAST}, {row_bytes}}};\n")
    print(f"{args.out}: {LAST - FIRST + 1} characters, {len(data)} bytes")


def data(args):
    with open(args.file, "rb") as f:
        content = f.read()
    with open(args.out, "w", newline="\n") as f:
        f.write(f"// Generated by scripts/ui_assets.py from {os.path.basename(args.file)}: {len(content)} bytes.\n")
        f.write("#pragma once\n\n")
        f.write(f"static const unsigned char {args.name}[] = {{\n{array(content, 16, '0x{:02X}')}\n}};\n")
    print(f"{args.out}: {len(content)} bytes")


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    commands = parser.add_subparsers(dest="command", required=True)
    p = commands.add_parser("font")
    p.add_argument("font")
    p.add_argument("size", type=int, help="pixels per em")
    p.add_argument("cell_w", type=int)
    p.add_argument("cell_h", type=int)
    p.add_argument("name", help="the ui_font_t's C name")
    p.add_argument("out")
    p.set_defaults(run=font)
    p = commands.add_parser("data")
    p.add_argument("file")
    p.add_argument("name", help="the array's C name")
    p.add_argument("out")
    p.set_defaults(run=data)
    args = parser.parse_args()
    args.run(args)


if __name__ == "__main__":
    main()
